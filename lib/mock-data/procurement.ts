function tl(
  rows: Array<[string, string, string, string, string]>,
): ProcurementTimelineEvent[] {
  return rows.map(([title, status, actor, description, timestamp], index) => ({
    id: `TL-${index + 1}`,
    title,
    status,
    actor,
    description,
    timestamp,
  }));
}

function aliases<T extends Omit<Procurement, "supplier" | "estCost" | "buyer">>(
  item: T,
): Procurement {
  return {
    ...item,
    supplier: item.sellerName ?? "Unassigned",
    estCost: item.estimatedCost,
    buyer: item.customerName,
  };
}

